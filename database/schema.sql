-- Country database schema for RediHealth (PostgreSQL 14+).
-- Holds one country's personal data: requests, staff, patients, meetings and the audit log.
-- The control database uses control-schema.sql; a single-database installation applies both.
-- "npm run migrate" applies this file on first run. Later changes go in database/migrations.
--
-- Conventions kept from the MySQL version so the application reads the same values:
--   * flags are SMALLINT 0/1, not BOOLEAN;
--   * NUMERIC values come back as strings, BIGINT ids as numbers;
--   * the former ENUM columns are VARCHAR with a CHECK constraint;
--   * updated_at is maintained by the set_updated_at() trigger (MySQL's ON UPDATE CURRENT_TIMESTAMP).

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- True when a JSON array of ids (patients.assigned_worker_ids) contains `wanted`, whether the ids
-- were stored as numbers or strings. Anything that is not an array contains nothing.
CREATE OR REPLACE FUNCTION jsonb_has_id(ids JSONB, wanted TEXT) RETURNS BOOLEAN AS $$
  SELECT CASE
    WHEN ids IS NULL OR jsonb_typeof(ids) <> 'array' THEN FALSE
    ELSE EXISTS (SELECT 1 FROM jsonb_array_elements_text(ids) AS element(value) WHERE btrim(element.value) = btrim(wanted))
  END
$$ LANGUAGE sql IMMUTABLE;

CREATE TABLE IF NOT EXISTS offline_sync_receipts (
  worker_id BIGINT NOT NULL,
  operation_id VARCHAR(36) NOT NULL,
  entity_id VARCHAR(64) NULL,
  revision VARCHAR(64) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (worker_id, operation_id)
);

CREATE TABLE IF NOT EXISTS medical_help_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(200),
  phone VARCHAR(50) NOT NULL,
  email VARCHAR(320) NULL,
  description TEXT NOT NULL,
  county VARCHAR(100) NULL,
  privacy_consent_at TIMESTAMPTZ NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'resolved', 'archived')),
  status_updated_by_name VARCHAR(200) NULL,
  status_updated_by_email VARCHAR(320) NULL,
  status_updated_at TIMESTAMPTZ NULL,
  priority VARCHAR(10) NOT NULL DEFAULT 'normal' CHECK (priority IN ('normal', 'urgent')),
  internal_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS medical_help_requests_created_at_idx ON medical_help_requests (created_at);
CREATE INDEX IF NOT EXISTS medical_help_requests_status_idx ON medical_help_requests (status, created_at);
CREATE OR REPLACE TRIGGER medical_help_requests_updated_at BEFORE UPDATE ON medical_help_requests
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS workers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(200) NOT NULL,
  email VARCHAR(320) NOT NULL,
  phone VARCHAR(50) NULL,
  role VARCHAR(100) NOT NULL DEFAULT 'Healthcare Worker',
  department VARCHAR(100) NULL,
  county VARCHAR(100) NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Case-insensitive, as MySQL's collation made it: one account per address however it is typed.
CREATE UNIQUE INDEX IF NOT EXISTS workers_email_unique_idx ON workers (LOWER(email));
CREATE OR REPLACE TRIGGER workers_updated_at BEFORE UPDATE ON workers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS patients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT,
  assigned_worker_id BIGINT NULL REFERENCES workers(id),
  assigned_worker_ids JSONB NULL,
  -- SHA-256 of the portal link token; the token itself is never stored.
  access_token_hash VARCHAR(64) NULL,
  access_token_expires_at TIMESTAMPTZ NULL,
  full_name VARCHAR(200) NOT NULL,
  phone VARCHAR(50) NOT NULL,
  email VARCHAR(320) NOT NULL,
  date_of_birth VARCHAR(50) NULL,
  gender VARCHAR(50) NULL,
  address VARCHAR(500) NULL,
  county VARCHAR(100) NULL,
  condition_notes TEXT NULL,
  medical_history TEXT NULL,
  profile_photo TEXT NULL,
  treatment_plan TEXT NULL,
  followups TEXT NULL,
  photos TEXT NULL,
  intake TEXT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'archived')),
  priority VARCHAR(10) NOT NULL DEFAULT 'moderate' CHECK (priority IN ('critical', 'high', 'moderate', 'low')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS patients_created_at_idx ON patients (created_at);
CREATE UNIQUE INDEX IF NOT EXISTS patients_email_unique_idx ON patients (LOWER(email));
CREATE INDEX IF NOT EXISTS patients_priority_idx ON patients (priority);
CREATE INDEX IF NOT EXISTS patients_assigned_worker_id_idx ON patients (assigned_worker_id);
CREATE UNIQUE INDEX IF NOT EXISTS patients_access_token_hash_unique_idx ON patients (access_token_hash);
CREATE INDEX IF NOT EXISTS patients_access_token_expires_idx ON patients (access_token_expires_at);
CREATE OR REPLACE TRIGGER patients_updated_at BEFORE UPDATE ON patients
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS mediator_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mediator_worker_id BIGINT NOT NULL REFERENCES workers(id),
  county VARCHAR(100) NOT NULL,
  locality VARCHAR(200) NULL,
  uat VARCHAR(200) NULL,
  full_name VARCHAR(200) NOT NULL,
  date_of_birth VARCHAR(50) NULL,
  phone VARCHAR(50) NULL,
  address VARCHAR(500) NULL,
  care_category VARCHAR(100) NOT NULL,
  urgency VARCHAR(10) NOT NULL DEFAULT 'moderate' CHECK (urgency IN ('low', 'moderate', 'high', 'urgent')),
  barriers JSONB NOT NULL,
  target_date DATE NULL,
  home_visit_date DATE NULL,
  map_lat NUMERIC(9, 6) NULL,
  map_lng NUMERIC(9, 6) NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  closed_at TIMESTAMPTZ NULL,
  closed_by_worker_id BIGINT NULL,
  notes TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS mediator_cases_worker_idx ON mediator_cases (mediator_worker_id);
CREATE INDEX IF NOT EXISTS mediator_cases_county_idx ON mediator_cases (county);
CREATE INDEX IF NOT EXISTS mediator_cases_target_date_idx ON mediator_cases (target_date);
CREATE OR REPLACE TRIGGER mediator_cases_updated_at BEFORE UPDATE ON mediator_cases
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

