-- Vitals from community hardware kits, doctors' care recommendations and mediator requests.
CREATE TABLE IF NOT EXISTS patient_vitals_telemetry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NULL,
  meeting_id BIGINT NULL,
  recorded_by_worker_id BIGINT NULL,
  device_kit_id VARCHAR(64) NOT NULL DEFAULT 'kit-standard',
  blood_pressure_systolic INT NULL,
  blood_pressure_diastolic INT NULL,
  pulse_bpm INT NULL,
  oxygen_saturation_pct INT NULL,
  blood_glucose_mg_dl NUMERIC(5, 1) NULL,
  glucose_context VARCHAR(15) DEFAULT 'random' CHECK (glucose_context IN ('fasting', 'postprandial', 'random')),
  body_temperature_c NUMERIC(4, 1) NULL,
  notes TEXT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS vitals_patient_idx ON patient_vitals_telemetry (patient_id);
CREATE INDEX IF NOT EXISTS vitals_meeting_idx ON patient_vitals_telemetry (meeting_id);
CREATE INDEX IF NOT EXISTS vitals_worker_idx ON patient_vitals_telemetry (recorded_by_worker_id);
CREATE INDEX IF NOT EXISTS vitals_recorded_at_idx ON patient_vitals_telemetry (recorded_at);

