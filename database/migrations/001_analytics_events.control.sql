-- Website statistics table in the control database (see control-schema.sql).
-- Website statistics (lib/analytics-server.ts). No IP address, no cookie, no personal data:
-- visitor_hash is a hash of IP + browser + a secret salt that changes every day, so a visitor can be
-- counted once per day but never followed from one day to the next. Rows are deleted after 13 months.
CREATE TABLE IF NOT EXISTS analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  kind VARCHAR(10) NOT NULL CHECK (kind IN ('pageview', 'event')),
  event_name VARCHAR(64) NULL,
  path VARCHAR(300) NOT NULL,
  lang VARCHAR(8) NULL,
  referrer_host VARCHAR(200) NULL,
  utm_source VARCHAR(100) NULL,
  utm_medium VARCHAR(100) NULL,
  utm_campaign VARCHAR(100) NULL,
  utm_term VARCHAR(100) NULL,
  utm_content VARCHAR(100) NULL,
  country VARCHAR(2) NULL,
  device VARCHAR(10) NULL CHECK (device IN ('mobile', 'tablet', 'desktop')),
  browser VARCHAR(20) NULL,
  os VARCHAR(20) NULL,
  visitor_hash VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS analytics_events_created_idx ON analytics_events (created_at);
CREATE INDEX IF NOT EXISTS analytics_events_kind_created_idx ON analytics_events (kind, created_at);
CREATE INDEX IF NOT EXISTS analytics_events_visitor_idx ON analytics_events (visitor_hash, created_at);
