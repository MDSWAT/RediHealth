-- Control database schema for RediHealth (PostgreSQL 14+). Holds nothing personal: rate-limit
-- counters, runtime settings, the public medical-institute directory and anonymised feedback.
-- Country databases use schema.sql; a single-database installation applies both files.
-- "npm run migrate" applies this file on first run. Later changes go in database/migrations.

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Shared rate limiting (works across server instances).
CREATE TABLE IF NOT EXISTS rate_limits (
  bucket_key VARCHAR(64) NOT NULL PRIMARY KEY,
  hits INT NOT NULL,
  reset_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS rate_limits_reset_at_idx ON rate_limits (reset_at);

-- Runtime settings editable by super admins (e.g. the operational alert recipient).
CREATE TABLE IF NOT EXISTS app_settings (
  setting_key VARCHAR(100) NOT NULL PRIMARY KEY,
  setting_value TEXT NULL,
  updated_by VARCHAR(320) NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE OR REPLACE TRIGGER app_settings_updated_at BEFORE UPDATE ON app_settings
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Medical institutes for the public Find help map (managed from /panel/institutes).
CREATE TABLE IF NOT EXISTS medical_institutes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country_code VARCHAR(2) NOT NULL,
  name VARCHAR(255) NOT NULL,
  category VARCHAR(32) NOT NULL DEFAULT 'clinic',
  address VARCHAR(500) NULL,
  city VARCHAR(160) NULL,
  phone VARCHAR(120) NULL,
  website VARCHAR(500) NULL,
  hours VARCHAR(255) NULL,
  emergency SMALLINT NOT NULL DEFAULT 0,
  lat NUMERIC(9, 6) NOT NULL,
  lng NUMERIC(9, 6) NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  source VARCHAR(16) NOT NULL DEFAULT 'manual',
  osm_ref VARCHAR(40) NULL,
  manually_edited SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS medical_institutes_osm_ref_uq ON medical_institutes (osm_ref);
CREATE INDEX IF NOT EXISTS medical_institutes_geo_idx ON medical_institutes (is_active, lat, lng);
CREATE INDEX IF NOT EXISTS medical_institutes_country_idx ON medical_institutes (country_code, is_active, category);
CREATE INDEX IF NOT EXISTS medical_institutes_name_idx ON medical_institutes (name);
CREATE OR REPLACE TRIGGER medical_institutes_updated_at BEFORE UPDATE ON medical_institutes
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Anonymized platform feedback and optional demographic evaluation store.
CREATE TABLE IF NOT EXISTS platform_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country_code VARCHAR(2) NOT NULL DEFAULT 'RO',
  lang VARCHAR(8) NOT NULL DEFAULT 'ro',
  page_path VARCHAR(255) NULL,
  rating_usefulness SMALLINT NOT NULL CHECK (rating_usefulness >= 0),
  rating_ease_of_use SMALLINT NOT NULL CHECK (rating_ease_of_use >= 0),
  rating_visual_design SMALLINT NOT NULL CHECK (rating_visual_design >= 0),
  rating_content_clarity SMALLINT NOT NULL CHECK (rating_content_clarity >= 0),
  rating_future_use SMALLINT NOT NULL CHECK (rating_future_use >= 0),
  open_feedback TEXT NULL,
  gender VARCHAR(32) NULL,
  age_group VARCHAR(24) NULL,
  locality VARCHAR(120) NULL,
  occupation VARCHAR(120) NULL,
  marital_status VARCHAR(32) NULL,
  anonymized_redactions SMALLINT NOT NULL DEFAULT 0 CHECK (anonymized_redactions >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS platform_feedback_created_idx ON platform_feedback (created_at);
CREATE INDEX IF NOT EXISTS platform_feedback_country_idx ON platform_feedback (country_code, created_at);
CREATE INDEX IF NOT EXISTS platform_feedback_lang_idx ON platform_feedback (lang, created_at);

-- Website statistics (lib/analytics-server.ts). No IP address, no cookie, no personal data:
-- visitor_hash is a hash of IP + browser + a secret salt that changes every day, so a visitor can be
-- counted once per day but never followed from one day to the next. Rows are deleted after 13 months.
CREATE TABLE IF NOT EXISTS analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  kind VARCHAR(10) NOT NULL CHECK (kind IN ('pageview', 'event')),
  event_name VARCHAR(64) NULL,
  path VARCHAR(300) NOT NULL,
  lang VARCHAR(8) NULL,
  referrer_host VARCHAR(200) NULL,
  utm_source VARCHAR(100) NULL,
  utm_medium VARCHAR(100) NULL,
  utm_campaign VARCHAR(100) NULL,
  utm_term VARCHAR(100) NULL,
  utm_content VARCHAR(100) NULL,
  country VARCHAR(2) NULL,
  device VARCHAR(10) NULL CHECK (device IN ('mobile', 'tablet', 'desktop')),
  browser VARCHAR(20) NULL,
  os VARCHAR(20) NULL,
  visitor_hash VARCHAR(32) NOT NULL,
  duration_ms INT NULL CHECK (duration_ms >= 0 AND duration_ms <= 3600000),
  scroll_depth SMALLINT NULL CHECK (scroll_depth >= 0 AND scroll_depth <= 100),
  target_key VARCHAR(120) NULL,
  target_label VARCHAR(120) NULL,
  target_kind VARCHAR(24) NULL
);
CREATE INDEX IF NOT EXISTS analytics_events_created_idx ON analytics_events (created_at);
CREATE INDEX IF NOT EXISTS analytics_events_kind_created_idx ON analytics_events (kind, created_at);
CREATE INDEX IF NOT EXISTS analytics_events_visitor_idx ON analytics_events (visitor_hash, created_at);
CREATE INDEX IF NOT EXISTS analytics_events_event_path_idx ON analytics_events (event_name, path, created_at) WHERE event_name IS NOT NULL;

-- Tagged ad links saved from the panel's Statistics page (lib/data/campaign-links.ts). Each URL is
-- rebuilt on the server from its fields, so only links to our own pages are stored.
CREATE TABLE IF NOT EXISTS campaign_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label VARCHAR(80) NOT NULL,
  campaign VARCHAR(60) NOT NULL,
  source VARCHAR(60) NOT NULL,
  medium VARCHAR(40) NOT NULL,
  content VARCHAR(60) NULL,
  path VARCHAR(100) NOT NULL,
  lang VARCHAR(8) NOT NULL,
  url VARCHAR(500) NOT NULL,
  created_by_email VARCHAR(320) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE OR REPLACE TRIGGER campaign_links_updated_at BEFORE UPDATE ON campaign_links
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE UNIQUE INDEX IF NOT EXISTS campaign_links_url_uq ON campaign_links (url);
CREATE INDEX IF NOT EXISTS campaign_links_campaign_idx ON campaign_links (campaign, created_at);
