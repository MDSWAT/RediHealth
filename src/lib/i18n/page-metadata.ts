export function localizedPageTitle(lang: Lang, key: PageMetadataKey, fallback: string): string {
  const localized = pageTitlesByLang[lang]?.[key];
  if (localized) return localized;
  return lang === "ro" ? (romanianPageTitles[key] ?? fallback) : fallback;
}

export function createPageMetadata(
  key: PageMetadataKey,
  title: string,
  description: string,
  extra: Metadata = {},
): () => Promise<Metadata> {
  return async () => ({
    ...extra,
    title: localizedPageTitle(await getRequestLang(), key, title),
    ...(description ? { description } : {}),
  });
}
